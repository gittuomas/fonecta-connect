def day_name(day_key: str, lang: str, fallback: str = "") -> str:
    return DAY_NAME.get(day_key, {}).get(lang) or fallback or day_key.replace("_", " ").title()


def date_label(d: date, lang: str) -> str:
    wd, mo = WEEKDAY[lang][d.weekday()], MONTH[lang][d.month - 1]
    if lang == "en":
        return f"{wd} {d.day} {mo}"
    if lang == "fi":
        return f"{wd} {d.day}. {mo}"
    if lang == "sv":
        return f"{wd} {d.day} {mo}"
    return f"{wd} {d.day}. {mo}"


def join(items: list[str], lang: str) -> str:
    items = [i for i in dict.fromkeys(items) if i]
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + f" {AND[lang]} " + items[-1]


def greeting(lang: str, **kw) -> str:
    return GREETING.get(lang, GREETING["en"]).format(**kw)


def voicemail(lang: str, **kw) -> str:
    return VOICEMAIL.get(lang, VOICEMAIL["en"]).format(**kw)
